"""Prove compiler-failure isolation using only the generated build header.

Run with no concurrent builds. The exact generated bytes are restored even when
an assertion fails, then the normal benchmark target is rebuilt.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[3]
out = Path(__file__).resolve().parent
header = root/'build-cuda/backend/cuda-provider/cuda_source.h'
original = header.read_bytes()
env = dict(os.environ)
env['PATH'] = str(root/'.tools/w64devkit/bin')+os.pathsep+env['PATH']
env.update(NYA_COMPUTE='cuda', NYA_CUDA_BLAS='0', NYA_CUDA_CUTLASS='0', NYA_CUDA_DEBUG='1')
records = []

def run(name, command, expected):
    result = subprocess.run(command, env=env, cwd=root, capture_output=True)
    (out/(name+'.log')).write_bytes(result.stdout+result.stderr)
    records.append({'name':name, 'command':command, 'exit_code':result.returncode, 'expected':expected})
    (out/'isolation.json').write_text(json.dumps(records, indent=2)+'\n', encoding='utf-8')
    assert result.returncode == expected, name

build = [str(root/'.tools/w64devkit/bin/cmake.exe'), '--build', 'build-cuda', '--target', 'nya-bench-training-device', '--parallel', '4']
exe = str(root/'build-cuda/nya-bench-training-device.exe')
for mode in ('inference','training'):
    run('isolation-baseline-'+mode, [exe,'--startup',mode], 0)
try:
    for poisoned in ('training','inference'):
        symbol = 'nya_cuda_training_source' if poisoned == 'training' else 'nya_cuda_source'
        marker = f'static const unsigned char {symbol}[] = {{'.encode()
        assert original.count(marker)==1
        fault = b'#error intentional_domain_isolation_test\n'
        prefix = ''.join(f'0x{b:02x},' for b in fault).encode()
        header.write_bytes(original.replace(marker,marker+prefix,1))
        run('isolation-build-'+poisoned,build,0)
        for mode in ('inference','training'):
            run('isolation-poison-'+poisoned+'-run-'+mode,[exe,'--startup',mode],1 if mode==poisoned else 0)
finally:
    header.write_bytes(original)
    run('isolation-restore-build',build,0)
    assert hashlib.sha256(header.read_bytes()).digest()==hashlib.sha256(original).digest()
for mode in ('inference','training'):
    run('isolation-restored-'+mode,[exe,'--startup',mode],0)
print('Independent compiler failures and restored device startup passed.',flush=True)
