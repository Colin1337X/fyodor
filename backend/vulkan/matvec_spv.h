/* SPIR-V for the F32 matvec below. Regenerate with glslang -V --target-env
 * vulkan1.0 -S comp -o matvec.spv matvec.comp, then encode little-endian words.
 * The shader is embedded so normal C builds need no shader compiler.
 * #version 450
 * layout(local_size_x = 64) in;
 * layout(set=0,binding=0,std430) readonly buffer Weights { float w[]; };
 * layout(set=0,binding=1,std430) readonly buffer Input { float x[]; };
 * layout(set=0,binding=2,std430) writeonly buffer Output { float y[]; };
 * layout(push_constant) uniform Shape { uint rows; uint columns; } shape;
 * shared float partial[64];
 * void main() {
 *     uint row = gl_WorkGroupID.x;
 *     uint lane = gl_LocalInvocationID.x;
 *     float sum = 0.0;
 *     for (uint col = lane; col < shape.columns; col += 64)
 *         sum += w[row * shape.columns + col] * x[col];
 *     partial[lane] = sum;
 *     barrier();
 *     for (uint stride = 32; stride > 0; stride >>= 1) {
 *         if (lane < stride) partial[lane] += partial[lane + stride];
 *         barrier();
 *     }
 *     if (lane == 0 && row < shape.rows) y[row] = partial[0];
 * }
 */
